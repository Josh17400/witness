const TOFU = [".######.", ...Array(8).fill(".#....#."), ".######."];

function bitmap(rows) {
  const m = new Uint8Array(CELL_W * CELL_H);
  rows.forEach((row, r) => { for (let c = 0; c < CELL_W; c++) if (row[c] === "#") m[(TOP + r) * CELL_W + c] = 1; });
  return m;
}

function parse() {
  const glyphs = new Map();
  const bands = BANDS.split(/\n\s*\n/).map((b) => b.split("\n").map((l) => l.trim()).filter((l) => l && !l.startsWith(";"))).filter((b) => b.length);
  let k = 0;
  for (const band of bands) {
    if (band.length !== ROWS) throw new Error(`font: a band has ${band.length} rows, expected ${ROWS}`);
    const cells = band.map((l) => l.split(" "));
    const n = cells[0].length;
    for (let i = 0; i < n; i++) {
      const rows = cells.map((c) => c[i]);
      if (rows.some((r) => !r || r.length !== CELL_W || /[^.#]/.test(r))) throw new Error(`font: malformed cell for ${JSON.stringify(ORDER[k])}`);
      glyphs.set(ORDER[k++], bitmap(rows));
    }
  }
  if (k !== ORDER.length) throw new Error(`font: drew ${k} glyphs for ${ORDER.length} characters`);
  return glyphs;
}

const GLYPHS = parse();
const TOFU_GLYPH = bitmap(TOFU);

/** Typographic look-alikes drawn with an existing glyph. */
const ALIASES = {
  "\t": " ", " ": " ", " ": " ", " ": " ", "−": "-", "‐": "-", "‑": "-", "‒": "–", "―": "—",
  "‘": "'", "’": "'", "‚": ",", "“": "\"", "”": "\"", "„": "\"", "•": "·", "∙": "·", "⋅": "·", "✕": "×", "✔": "✓",
  "✘": "✗", "△": "▲", "▽": "▼", "○": "●", "□": "■", "μ": "µ", "∆": "Δ", "♫": "♪", "⇒": "→", "⟶": "→",
};

/** The 8x16 ink mask (1 = ink, row-major) for a character; a box for unknown characters. */
export function glyph(ch) {
  return GLYPHS.get(ch) || GLYPHS.get(ALIASES[ch]) || TOFU_GLYPH;
}

/** True when the font can draw `ch` (directly or through a look-alike). */
export const hasGlyph = (ch) => GLYPHS.has(ch) || GLYPHS.has(ALIASES[ch]);

/** Every character the font covers, in order. */
export const CHARSET = ORDER.join("");
